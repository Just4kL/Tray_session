//! Деактиватор как отдельный исполняемый файл: `_uninstall.exe`.
//!
//! Собирается вторым бинарником того же пакета, но переиспользует модули
//! `log` и `uninstall` через `#[path]`: выносить их в библиотеку ради двух
//! файлов нецелесообразно, а дублировать логирование нельзя — иначе деактиватор
//! и программа будут писать логи по разным правилам.
//!
//! Имя бинарника в cargo — `uninstall`; при сборке установщика он копируется
//! как `_uninstall.exe` (с подчёркиванием, чтобы файл не спутать с программой).

#[path = "../log.rs"]
mod log;

#[path = "../uninstall.rs"]
mod uninstall;

fn main() {
    uninstall::main();
}
