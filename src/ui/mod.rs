//! Модульный UI.
//!
//! Presentation-слой выносится из `app.rs` инкрементально, каждый этап
//! оставляет сборку зелёной:
//!
//! * `theme` — токены оформления и скины (фаза 1);
//! * `layout` — каркас раскладки: единственный владелец панелей
//!   `SidePanel`/`TopBottomPanel`/`CentralPanel` (фаза 2);
//! * `views` — разделы-вкладки (фаза 3);
//! * `widgets` — переиспользуемые виджеты.
//!
//! На этапе 3.0 здесь только пустые контейнеры `Views` и `ThemeManager`,
//! чтобы `TrackerApp` уже хранил их, а фазы 1 и 3 их только наполняли
//! без повторных правок структуры приложения.

pub mod layout;
pub mod theme;
pub mod views;
pub mod widgets;
